"""Plain-language PDF audit report (Stage 4).

Written for someone who is *not* the person who ran the scanner -- a team lead,
a client, a security reviewer. Every finding is explained in ordinary words,
with the technical snippet kept secondary.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    HRFlowable,
    PageBreak,
    Paragraph,
    Preformatted,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.llm_remediation.schemas import AuditRemediationReport
from app.static_scanner.engine import ScanResult

